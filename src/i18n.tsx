let activeLocale: ResolvedLocale = 'zh-CN'

export function resolveLocale(
  preference: AppSettings['language'],
): ResolvedLocale {
  if (preference !== 'system') return preference
  return navigator.language.toLocaleLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

export const translateForLocale = (
  locale: ResolvedLocale,
  source: string,
  values: Record<string, string | number> = {},
) => {
  const template = locale === 'en-US' ? english[source] ?? source : source
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  )
}

export const translate: Translator = (source, values) =>
  translateForLocale(activeLocale, source, values)

export function setCurrentLocale(locale: ResolvedLocale) {
  activeLocale = locale
}

export function getCurrentLocale() {
  return activeLocale
}

const LocaleContext = createContext<{
  locale: ResolvedLocale
  t: Translator
}>({
  locale: 'zh-CN',
  t: translate,
})

export function I18nProvider({
  locale,
  children,
}: {
  locale: ResolvedLocale
  children: ReactNode
}) {
  useEffect(() => {
    setCurrentLocale(locale)
    document.documentElement.lang = locale
  }, [locale])
  const value = useMemo(
    () => ({
      locale,
      t: (source: string, values?: Record<string, string | number>) =>
        translateForLocale(locale, source, values),
    }),
    [locale],
  )
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useI18n() {
  return useContext(LocaleContext)
}
